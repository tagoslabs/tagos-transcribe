def get_lang() -> str:
    return LANG


def load_lang() -> str:
    try:
        value = LANG_FILE.read_text(encoding="utf-8").strip()
    except OSError:
        return "en"
    return value if value in STRINGS else "en"


def set_lang(code: str) -> None:
    global LANG
    if code not in STRINGS:
        code = "en"
    LANG = code
    try:
        LANG_FILE.write_text(code, encoding="utf-8")
    except OSError:
        pass


def t(key: str, **kwargs: object) -> str:
    text = STRINGS.get(LANG, STRINGS["en"]).get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text


def idle_statuses() -> set[str]:
    return {"", *(pack["status_ready"] for pack in STRINGS.values())}


def preview_placeholders() -> set[str]:
    return {pack["preview_placeholder"] for pack in STRINGS.values()}


def no_file_labels() -> set[str]:
    return {pack["no_file"] for pack in STRINGS.values()}


def all_values(key: str) -> set[str]:
    return {pack[key] for pack in STRINGS.values() if key in pack}
